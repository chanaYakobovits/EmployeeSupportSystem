import { Location } from '@angular/common';
import {
  ChangeDetectionStrategy,
  Component,
  DestroyRef,
  ElementRef,
  Injector,
  afterNextRender,
  computed,
  effect,
  inject,
  input,
  signal,
  untracked,
} from '@angular/core';
import { takeUntilDestroyed } from '@angular/core/rxjs-interop';
import {
  AbstractControl,
  FormControl,
  FormGroup,
  ReactiveFormsModule,
  ValidationErrors,
  Validators,
} from '@angular/forms';
import { MatButtonModule } from '@angular/material/button';
import { MatCheckboxModule } from '@angular/material/checkbox';
import { MatDialog } from '@angular/material/dialog';
import { MatFormFieldModule } from '@angular/material/form-field';
import { MatIconModule } from '@angular/material/icon';
import { MatInputModule } from '@angular/material/input';
import { MatProgressSpinnerModule } from '@angular/material/progress-spinner';
import { MatSelectModule } from '@angular/material/select';
import { Router, RouterLink, UrlTree } from '@angular/router';
import { filter, switchMap } from 'rxjs';

import { AuthService } from '../../../../core/auth/auth.service';
import { Role } from '../../../../core/models/auth.models';
import { CreateUserRequest, UserDetails, fullName } from '../../../../core/models/user.models';
import { NotificationService } from '../../../../core/notifications/notification.service';
import { ActiveBadge } from '../../../../shared/components/active-badge/active-badge';
import { Badge } from '../../../../shared/components/badge/badge';
import { ConfirmService } from '../../../../shared/components/confirm-dialog/confirm.service';
import { EmptyState } from '../../../../shared/components/empty-state/empty-state';
import { ErrorState } from '../../../../shared/components/error-state/error-state';
import { FormAlert, FormAlertBox } from '../../../../shared/components/form-alert/form-alert';
import { LoadingState } from '../../../../shared/components/loading-state/loading-state';
import { PageHeader } from '../../../../shared/components/page-header/page-header';
import { applyServerErrors } from '../../../../shared/forms/server-errors';
import { DateTimePipe } from '../../../../shared/pipes/date-time.pipe';
import { DEPARTMENTS_URL, USERS_URL, adminAlert, unassignedTicketsMessage } from '../../admin-errors';
import { openTemporaryPasswordDialog } from '../temp-password-dialog/temp-password-dialog';
import { UserFormStore } from './user-form.store';

/** Roles chosen on this screen. Employee is implied; DepartmentManager follows from the departments screen. */
export const EDITABLE_ROLES = ['Handler', 'Executive', 'Admin'] as const;

/** Same rule as the server (RuleBuilderExtensions.ValidEmail). */
const EMAIL_PATTERN = /^[^@\s]+@[^@\s]+\.[^@\s]+$/;

/** Required, and not only spaces. */
function requiredText(control: AbstractControl<string>): ValidationErrors | null {
  return control.value?.trim() ? null : { required: true };
}

function textControl(maxLength: number): FormControl<string> {
  return new FormControl('', { nonNullable: true, validators: [requiredText, Validators.maxLength(maxLength)] });
}

/** Order used to focus the first invalid field. */
const FIELD_ORDER = ['firstName', 'lastName', 'email', 'departmentId', 'jobTitle', 'roles'] as const;

/**
 * Create / edit a user (spec 4.2, 7.8): /admin/users/new and /admin/users/:id.
 * Edit mode adds reset password and deactivate / activate, with a confirmation.
 */
@Component({
  selector: 'app-user-form',
  imports: [
    ReactiveFormsModule,
    RouterLink,
    MatButtonModule,
    MatCheckboxModule,
    MatFormFieldModule,
    MatIconModule,
    MatInputModule,
    MatProgressSpinnerModule,
    MatSelectModule,
    PageHeader,
    LoadingState,
    ErrorState,
    EmptyState,
    FormAlertBox,
    ActiveBadge,
    Badge,
    DateTimePipe,
  ],
  providers: [UserFormStore],
  changeDetection: ChangeDetectionStrategy.OnPush,
  templateUrl: './user-form.html',
  styleUrl: './user-form.scss',
})
export class UserForm {
  /** Route parameter :id; undefined on /admin/users/new. */
  readonly id = input<string>();

  protected readonly store = inject(UserFormStore);
  private readonly auth = inject(AuthService);
  private readonly router = inject(Router);
  private readonly dialog = inject(MatDialog);
  private readonly confirm = inject(ConfirmService);
  private readonly notifications = inject(NotificationService);
  private readonly destroyRef = inject(DestroyRef);
  private readonly injector = inject(Injector);
  private readonly host = inject<ElementRef<HTMLElement>>(ElementRef);
  private readonly location = inject(Location);

  protected readonly departmentsUrl = DEPARTMENTS_URL;
  protected readonly form = new FormGroup({
    // Generated by the server and never changes (spec 4.2): disabled, so it is not in form.value and never sent.
    employeeCode: new FormControl({ value: '', disabled: true }, { nonNullable: true }),
    firstName: textControl(50),
    lastName: textControl(50),
    email: new FormControl('', {
      nonNullable: true,
      validators: [requiredText, Validators.maxLength(256), Validators.pattern(EMAIL_PATTERN)],
    }),
    departmentId: new FormControl<number | null>(null, Validators.required),
    jobTitle: textControl(100),
    roles: new FormGroup({
      Handler: new FormControl(false, { nonNullable: true }),
      Executive: new FormControl(false, { nonNullable: true }),
      Admin: new FormControl(false, { nonNullable: true }),
    }),
  });

  protected readonly alert = signal<FormAlert | null>(null);
  protected readonly isEdit = computed(() => this.id() !== undefined);
  protected readonly user = this.store.user;
  protected readonly userName = computed(() => {
    const user = this.user();
    return user ? fullName(user) : '';
  });
  /** The signed-in admin: cannot deactivate themself, remove their own Admin role or reset their own password. */
  protected readonly isSelf = computed(() => {
    const user = this.user();
    return user !== null && user.id === this.auth.currentUser()?.id;
  });
  protected readonly isDepartmentManager = computed(() => this.user()?.roles.includes('DepartmentManager') ?? false);
  protected readonly isHandler = computed(() => this.user()?.roles.includes('Handler') ?? false);

  /** Back to the list as it was (search, filters, page) when the user came from there. */
  protected readonly backLink: UrlTree;

  constructor() {
    this.backLink = this.router.parseUrl(this.returnUrl());

    // Route parameter → load (also when moving from /new to /:id after creating).
    effect(() => {
      const id = this.id();
      untracked(() => this.loadFor(id));
    });

    // Loaded or saved → show the server's values.
    effect(() => {
      const user = this.store.editable();
      untracked(() => this.resetForm(user));
    });

    // Your own Admin role cannot be removed (CLAUDE.md) – the control is locked, its value is still sent.
    effect(() => {
      const admin = this.form.controls.roles.controls.Admin;
      if (this.isSelf()) {
        admin.disable({ emitEvent: false });
      } else {
        admin.enable({ emitEvent: false });
      }
    });
  }

  protected reload(): void {
    this.loadFor(this.id());
  }

  protected submit(): void {
    if (this.store.saving()) {
      return;
    }
    this.alert.set(null);
    if (this.form.invalid) {
      this.form.markAllAsTouched();
      this.focusFirstInvalid();
      return;
    }

    const request = this.buildRequest();
    const user = this.user();
    if (this.isEdit() && user) {
      this.store
        .update(user.id, request)
        .pipe(takeUntilDestroyed(this.destroyRef))
        .subscribe({
          next: () => this.notifications.success('השינויים נשמרו'),
          error: (error: unknown) => this.showSaveError(error),
        });
      return;
    }

    this.store
      .create(request)
      .pipe(takeUntilDestroyed(this.destroyRef))
      .subscribe({
        next: (response) => {
          const created = response.user;
          openTemporaryPasswordDialog(this.dialog, {
            employeeCode: created.employeeCode,
            fullName: fullName(created),
            temporaryPassword: response.temporaryPassword,
            reason: 'created',
          })
            .afterClosed()
            .subscribe(() => {
              void this.router.navigate([USERS_URL, created.id], {
                replaceUrl: true,
                state: { returnTo: this.router.serializeUrl(this.backLink) },
              });
            });
        },
        error: (error: unknown) => this.showSaveError(error),
      });
  }

  protected resetPassword(): void {
    const user = this.user();
    if (!user || this.isSelf()) {
      return;
    }
    this.alert.set(null);
    this.confirm
      .confirm({
        heading: 'איפוס סיסמה',
        message: `תיווצר סיסמה זמנית חדשה עבור ${fullName(user)}.`,
        consequences: [
          'הסיסמה הנוכחית תפסיק לעבוד מיד.',
          'העובד ינותק מכל המכשירים שבהם הוא מחובר.',
          'בכניסה הבאה המערכת תבקש לבחור סיסמה חדשה.',
        ],
        confirmText: 'איפוס הסיסמה',
        tone: 'danger',
      })
      .pipe(
        filter(Boolean),
        switchMap(() => this.store.resetPassword(user.id)),
        takeUntilDestroyed(this.destroyRef),
      )
      .subscribe({
        next: (response) =>
          openTemporaryPasswordDialog(this.dialog, {
            employeeCode: user.employeeCode,
            fullName: fullName(user),
            temporaryPassword: response.temporaryPassword,
            reason: 'reset',
          }),
        error: (error: unknown) => this.alert.set(adminAlert(error)),
      });
  }

  protected toggleActive(): void {
    const user = this.user();
    if (!user || this.isSelf()) {
      return;
    }
    this.alert.set(null);
    const deactivate = user.isActive;
    this.confirm
      .confirm(deactivate ? this.deactivateConfirmation(user) : this.activateConfirmation(user))
      .pipe(
        filter(Boolean),
        switchMap(() => this.store.setActive(user.id, !deactivate)),
        takeUntilDestroyed(this.destroyRef),
      )
      .subscribe({
        next: (response) => {
          const message = deactivate
            ? `העובד הושבת. ${unassignedTicketsMessage(response.unassignedTicketCount)}`.trim()
            : 'העובד הופעל';
          this.notifications.success(message);
        },
        error: (error: unknown) => this.alert.set(adminAlert(error)),
      });
  }

  private deactivateConfirmation(user: UserDetails) {
    const consequences = ['לא תתאפשר כניסה למערכת, והחיבורים הקיימים יבוטלו (חיבור פתוח עשוי להישאר תקף עד 15 דקות).'];
    if (user.roles.includes('Handler')) {
      consequences.push('פניות לא פתורות שמוקצות לעובד יחזרו לתור המחלקה.');
    }
    consequences.push('העובד לא יימחק: הפרטים וההיסטוריה שלו נשמרים, ואפשר להפעיל אותו מחדש.');
    return {
      heading: 'השבתת עובד',
      message: `${fullName(user)} יסומן כלא פעיל.`,
      consequences,
      confirmText: 'השבתה',
      tone: 'danger' as const,
    };
  }

  private activateConfirmation(user: UserDetails) {
    return {
      heading: 'הפעלת עובד',
      message: `${fullName(user)} יוכל להתחבר שוב למערכת עם הסיסמה הקיימת שלו.`,
      confirmText: 'הפעלה',
    };
  }

  private loadFor(id: string | undefined): void {
    this.alert.set(null);
    if (id === undefined) {
      this.store.load(null);
      return;
    }
    const numericId = /^[1-9]\d{0,9}$/.test(id) ? Number(id) : null;
    if (numericId === null) {
      this.store.markNotFound();
    } else {
      this.store.load(numericId);
    }
  }

  private resetForm(user: UserDetails | null): void {
    this.form.reset({
      employeeCode: user?.employeeCode ?? '',
      firstName: user?.firstName ?? '',
      lastName: user?.lastName ?? '',
      email: user?.email ?? '',
      departmentId: user?.department.id ?? null,
      jobTitle: user?.jobTitle ?? '',
      roles: {
        Handler: user?.roles.includes('Handler') ?? false,
        Executive: user?.roles.includes('Executive') ?? false,
        Admin: user?.roles.includes('Admin') ?? false,
      },
    });
  }

  /** Employee is always sent; DepartmentManager is sent exactly as the server has it (never added or removed here). */
  private buildRequest(): CreateUserRequest {
    const value = this.form.getRawValue();
    const roles: Role[] = ['Employee'];
    for (const role of EDITABLE_ROLES) {
      if (value.roles[role]) {
        roles.push(role);
      }
    }
    if (this.isDepartmentManager()) {
      roles.push('DepartmentManager');
    }
    return {
      firstName: value.firstName.trim(),
      lastName: value.lastName.trim(),
      email: value.email.trim(),
      departmentId: value.departmentId ?? 0,
      jobTitle: value.jobTitle.trim(),
      roles,
    };
  }

  /** 400 / 409 next to the fields (e.g. the e-mail is taken); anything else in the alert at the top. */
  private showSaveError(error: unknown): void {
    const applied = applyServerErrors(this.form, error);
    if (applied.fields.length > 0 && applied.unmatched.length === 0) {
      this.focusField(applied.fields[0]);
      return;
    }
    const alert = adminAlert(error);
    if (applied.unmatched.length > 0) {
      alert.detail = applied.unmatched.join(' ');
    }
    this.alert.set(alert);
  }

  private focusFirstInvalid(): void {
    const name = FIELD_ORDER.find((field) => this.form.controls[field].invalid);
    if (name) {
      this.focusField(name);
    }
  }

  private focusField(name: string): void {
    afterNextRender(
      () => {
        const root = this.host.nativeElement;
        const element =
          root.querySelector<HTMLElement>(`[formControlName="${name}"]`) ??
          root.querySelector<HTMLElement>(`[data-field="${name}"] input:not([disabled])`);
        element?.focus();
      },
      { injector: this.injector },
    );
  }

  private returnUrl(): string {
    const state = (this.router.getCurrentNavigation()?.extras.state ?? this.location.getState()) as
      | { returnTo?: unknown }
      | null
      | undefined;
    const returnTo = state?.returnTo;
    // Only back to the users list – never an arbitrary URL from the history state.
    return typeof returnTo === 'string' && /^\/admin\/users(\?|$)/.test(returnTo) ? returnTo : USERS_URL;
  }
}
